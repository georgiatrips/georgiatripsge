/**
 * Returns the localized document title for a given pathname and language.
 * If pathname is a dynamic route (e.g. /tours/[id] or /places/[id]), returns null
 * so the detail component can set the specific title with the entity's name.
 */
export function getStaticPageTitle(pathname, lang = "ka") {
  const dict = PAGE_TITLES[lang] || PAGE_TITLES.ka;
  if (!pathname) return dict.home;

  const clean = pathname.replace(/^\/(?:ka|en|ru|tr|ar)(?=\/|$)/, "") || "/";

  if (clean === "/" || clean === "") return dict.home;
  if (clean === "/tours") return dict.tours;
  if (clean === "/places") return dict.places;
  if (clean === "/transfers" || clean === "/transport") return dict.transfers;
  if (clean === "/hotels") return dict.hotels;
  if (clean === "/posts") return dict.posts;
  if (clean === "/coupons") return dict.coupons;
  if (clean === "/privacy-policy") return dict.privacy;
  if (clean === "/terms") return dict.terms;
  if (clean === "/login") return dict.login;
  if (clean.startsWith("/booking")) return dict.booking;
  if (clean.startsWith("/admin")) return dict.admin;

  // Dynamic pages return fallback or null (detail client overrides it)
  if (clean.startsWith("/tours/")) return null; // handled by TourDetailClient
  if (clean.startsWith("/places/")) return null; // handled by PlaceDetailClient

  return null;
}
